#!/usr/bin/env python3
"""Parse ROVER's calib_t265.yaml into the normalized calib_t265.yaml (written to tools/rover/calib/ and data/rover/)."""
import os, shutil, yaml
import rovercalib as rc

d = rc.build_normalized()
os.makedirs(os.path.dirname(rc.DATA_NORM), exist_ok=True)
for p in (rc.NORM, rc.DATA_NORM):
    with open(p, "w") as f:
        f.write("# Normalized ROVER T265 calibration (generated by tools/rover/make_calib.py)\n")
        yaml.safe_dump(d, f, sort_keys=False, default_flow_style=None)
    print("wrote", p)
print(d["conventions"]["verification"]); print(d["prism"])
