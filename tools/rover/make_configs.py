#!/usr/bin/env python3
"""Emit method configs for ROVER T265 (cam0 = left fisheye, mono-inertial) from the normalized calibration.

Usage: .venv/bin/python tools/rover/make_configs.py [--noise-scale 2] [--walk-scale 2] [--rect-size 640 480] [--rect-hfov 100]

Reads tools/rover/calib/calib_t265.yaml (or data/rover/calib_t265.yaml) and the generic templates
methods/{openvins,orbslam3,dbafusion}/... (text-substituted so that comments/format survive), writes:
  tools/rover/generated/openvins/{estimator_config,kalibr_imucam_chain,kalibr_imu_chain}.yaml   (equidistant, mono)
  tools/rover/generated/orbslam3/rover_t265_mono_inertial.yaml                       (KannalaBrandt8, 848x800 native)
  tools/rover/generated/dbafusion/rover_t265.yaml     (PINHOLE-RECTIFIED cam0 -> run tools/rover/undistort_asl.py first,
                                                       same --size/--hfov as here)
IMU noise inflation (documented, parameters): sigma_used = scale * Kalibr value, separately for the noise densities
(--noise-scale, default 2) and the bias random walks (--walk-scale, default 2). The Kalibr values shipped with ROVER are
already large for a BMI055 (gyro 3.2e-3, acc 1.7e-2, acc walk 1.2e-2), so 2 (low end of the usual x2-x5) is the default.
Topics: /cam0/image_raw (mono8), /imu0  (what tools/rover/asl_to_bag.py writes).
"""
import argparse, os, re
import numpy as np, yaml
import rovercalib as rc

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(HERE, "generated")


def fmt(v):
    return repr(float(v)) if not isinstance(v, str) else v


def set_key(text, key, value, sep=": "):
    """Replace the value of a top-level 'key: value  # comment' line (keeps the comment). value None -> delete line."""
    pat = re.compile(r"^(%s:\s*)([^#\n]*?)(\s*(#.*)?)$" % re.escape(key), re.M)
    if not pat.search(text):
        raise KeyError(key)
    if value is None:
        return pat.sub("", text, count=1)
    return pat.sub(lambda m: m.group(1) + str(value) + (("  " + m.group(4)) if m.group(4) else ""), text, count=1)


def cv_clean(text, header):
    """OpenCV FileStorage-safe YAML: '%YAML:1.0' first line, header comment after it, no trailing comments on value lines
    (they are moved to their own comment line above)."""
    out = []
    for l in text.splitlines():
        if l.startswith("%YAML") or l.startswith("# GENERATED"):
            continue
        m = re.match(r"^(\s*)([A-Za-z_][\w.\-]*:)(\s*[^#\n]*?)\s*#(.*)$", l)
        if m and not l.lstrip().startswith("#"):
            ind, key, val, com = m.groups()
            out.append(f"{ind}# {com.strip()}")
            out.append(f"{ind}{key}{val}".rstrip())
        else:
            out.append(l)
    return "%YAML:1.0\n" + "".join(f"# {h}\n" for h in header.strip().splitlines()) + "\n".join(out).lstrip("\n") + "\n"


def mat_rows(T, indent="    "):
    return "\n".join(f"{indent}- [" + ", ".join(f"{x:.12g}" for x in r) + "]" for r in T)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--noise-scale", type=float, default=2.0)
    ap.add_argument("--walk-scale", type=float, default=2.0)
    ap.add_argument("--rect-size", type=int, nargs=2, default=[640, 480])
    ap.add_argument("--rect-hfov", type=float, default=100.0)
    a = ap.parse_args()
    c = rc.load()
    cam, imu = c["cam0"], c["imu"]
    W, H = cam["resolution"]
    fx, fy, cx, cy = cam["intrinsics"]; k = cam["distortion"]
    T_ic = np.array(cam["T_imu_cam"])
    gn, an = imu["gyroscope_noise_density"] * a.noise_scale, imu["accelerometer_noise_density"] * a.noise_scale
    gw, aw = imu["gyroscope_random_walk"] * a.walk_scale, imu["accelerometer_random_walk"] * a.walk_scale

    # ---------------- OpenVINS
    d = os.path.join(OUT, "openvins"); os.makedirs(d, exist_ok=True)
    t = open(os.path.join(REPO, "methods/openvins/config/TEMPLATE_ground_robot/estimator_config.yaml")).read()
    for key, val in dict(use_stereo="false", max_cameras="1", num_pts="300", zupt_max_velocity="0.2",
                         track_frequency="25.0", calib_cam_extrinsics="false", calib_cam_intrinsics="false",
                         calib_cam_timeoffset="true", init_dyn_use="true", init_window_time="2.0").items():
        t = set_key(t, key, val)
    open(os.path.join(d, "estimator_config.yaml"), "w").write(
        "# GENERATED by tools/rover/make_configs.py from calib_t265.yaml -- ROVER T265 mono-inertial\n" + t)
    open(os.path.join(d, "kalibr_imucam_chain.yaml"), "w").write(f"""%YAML:1.0
# GENERATED by tools/rover/make_configs.py. ROVER RealSense T265 left fisheye (equidistant), mono.
cam0:
  T_imu_cam: #rotation from camera to IMU R_CtoI, position of camera in IMU p_CinI  (= inv(IMU-To-CamLeft))
{mat_rows(T_ic)}
  cam_overlaps: []
  camera_model: pinhole
  distortion_coeffs: [{', '.join(repr(x) for x in k)}]
  distortion_model: equidistant
  intrinsics: [{fx!r}, {fy!r}, {cx!r}, {cy!r}] #fu, fv, cu, cv
  resolution: [{W}, {H}]
  rostopic: /cam0/image_raw
""")
    t = open(os.path.join(REPO, "methods/openvins/config/TEMPLATE_ground_robot/kalibr_imu_chain.yaml")).read()
    t = re.sub(r"(accelerometer_noise_density:\s*)\S+", lambda m: m.group(1) + f"{an:.6e}", t)
    t = re.sub(r"(accelerometer_random_walk:\s*)\S+", lambda m: m.group(1) + f"{aw:.6e}", t)
    t = re.sub(r"(gyroscope_noise_density:\s*)\S+", lambda m: m.group(1) + f"{gn:.6e}", t)
    t = re.sub(r"(gyroscope_random_walk:\s*)\S+", lambda m: m.group(1) + f"{gw:.6e}", t)
    t = re.sub(r"(rostopic:\s*)\S+", r"\g<1>/imu0", t); t = re.sub(r"(update_rate:\s*)\S+", r"\g<1>200.0", t)
    open(os.path.join(d, "kalibr_imu_chain.yaml"), "w").write(
        f"# GENERATED: Kalibr values x{a.noise_scale} (noise) / x{a.walk_scale} (walk)\n" + t)

    # ---------------- ORB-SLAM3
    d = os.path.join(OUT, "orbslam3"); os.makedirs(d, exist_ok=True)
    t = open(os.path.join(REPO, "methods/orbslam3/config/TEMPLATE_ground_robot.yaml")).read()
    t = set_key(t, "Camera.type", '"KannalaBrandt8"')
    for key, v in (("fx", fx), ("fy", fy), ("cx", cx), ("cy", cy)):
        t = set_key(t, f"Camera1.{key}", fmt(v))
    for i, kk in enumerate(k):
        t = set_key(t, f"Camera1.k{i+1}", fmt(kk)) if i < 2 else t
    t = set_key(t, "Camera1.p1", fmt(k[2])).replace("Camera1.p1:", "Camera1.k3:", 1)
    t = set_key(t, "Camera1.p2", fmt(k[3])).replace("Camera1.p2:", "Camera1.k4:", 1)
    for key in ("fx", "fy", "cx", "cy", "k1", "k2", "p1", "p2"):
        t = set_key(t, f"Camera2.{key}", None)
    t = set_key(t, "Camera.width", W); t = set_key(t, "Camera.height", H)
    t = set_key(t, "Camera.newWidth", None); t = set_key(t, "Camera.newHeight", None)
    t = set_key(t, "Camera.fps", 30)
    t = re.sub(r"Stereo\.T_c1_c2: !!opencv-matrix.*?\n\n", "", t, flags=re.S)
    t = set_key(t, "Stereo.ThDepth", None)
    t = re.sub(r"(IMU\.T_b_c1: !!opencv-matrix\n\s*rows: 4\n\s*cols: 4\n\s*dt: f\n\s*data: )\[.*?\]",
               lambda m: m.group(1) + "[" + ",\n         ".join(", ".join(f"{x:.12g}" for x in r) for r in T_ic) + "]", t, flags=re.S)
    t = set_key(t, "IMU.NoiseGyro", f"{gn:.6e}"); t = set_key(t, "IMU.NoiseAcc", f"{an:.6e}")
    t = set_key(t, "IMU.GyroWalk", f"{gw:.6e}"); t = set_key(t, "IMU.AccWalk", f"{aw:.6e}")
    t = set_key(t, "IMU.Frequency", "200.0")
    t = set_key(t, "ORBextractor.nFeatures", "1500")
    t = t.replace("  # (if k3 present for PinHole: Camera1.k3)", "")
    t = re.sub(r"\n{3,}", "\n\n", t)
    open(os.path.join(d, "rover_t265_mono_inertial.yaml"), "w").write(
        "# GENERATED by tools/rover/make_configs.py (ROVER T265 left fisheye, KannalaBrandt8, mono-inertial)\n"
        "# NOTE: Camera.k3/k4 are KB8 coefficients; ORB-SLAM3 v1.0 reads Camera1.k1..k4.\n" + t)

    # ---------------- DBA-Fusion (rectified pinhole)
    d = os.path.join(OUT, "dbafusion"); os.makedirs(d, exist_ok=True)
    tm = yaml.safe_load(open(os.path.join(REPO, "methods/dbafusion/configs/TEMPLATE_ground_robot.yaml")))
    r = rc.rectified(c, tuple(a.rect_size), a.rect_hfov)
    tm["dataset"] = "rover_t265"
    tm["camera"] = dict(model="none", fx=r["fx"], fy=r["fy"], cx=r["cx"], cy=r["cy"], distortion=[0.0, 0.0, 0.0, 0.0],
                        width=r["width"], height=r["height"])
    tm["T_imu_cam"] = [float(x) for x in T_ic.reshape(-1)]
    tm["imu"].update(rate_hz=200, gyro_unit="rad_s",
                     datasheet=dict(accel_noise_density=imu["accelerometer_noise_density"], gyro_noise_density=imu["gyroscope_noise_density"],
                                    accel_random_walk=imu["accelerometer_random_walk"], gyro_random_walk=imu["gyroscope_random_walk"]),
                     dbaf_noise=[an, gn, aw, gw])
    tm["stride"] = 4          # 30 Hz / 4 = 7.5 Hz keyframe candidates
    tm["clahe"] = True
    tm["dbaf"]["translation_threshold"] = 0.1   # robot at ~0.5 m/s
    with open(os.path.join(d, "rover_t265.yaml"), "w") as f:
        f.write("# GENERATED by tools/rover/make_configs.py. Images must be the RECTIFIED pinhole cam0 from\n"
                f"# tools/rover/undistort_asl.py --size {r['width']} {r['height']} --hfov {r['hfov_deg']} (equidistant fisheye -> pinhole, R=I,\n"
                "# so T_imu_cam is unchanged). dbaf_noise = [acc, gyro, acc_rw, gyro_rw] = Kalibr values x scale (UNTUNED, see README).\n")
        yaml.safe_dump(tm, f, sort_keys=False, default_flow_style=None)
    for rel in ("openvins/estimator_config.yaml", "openvins/kalibr_imucam_chain.yaml", "openvins/kalibr_imu_chain.yaml",
                "orbslam3/rover_t265_mono_inertial.yaml"):
        pth = os.path.join(OUT, rel)
        raw_txt = open(pth).read()
        open(pth, "w").write(cv_clean(raw_txt, "GENERATED by tools/rover/make_configs.py from calib_t265.yaml (ROVER T265, mono-inertial; "
                                      f"IMU noise x{a.noise_scale}, walk x{a.walk_scale})"))
    print("generated ->", OUT, "| rectified K:", {k_: r[k_] for k_ in ("fx", "fy", "cx", "cy", "width", "height")})
    print(f"IMU used: gyro_nd={gn:.3e} acc_nd={an:.3e} gyro_rw={gw:.3e} acc_rw={aw:.3e}")


if __name__ == "__main__":
    main()
